export type MessageKey = keyof typeof MESSAGES.en;

export function isLocale(value: unknown): value is Locale {
  return value === "en" || value === "ar";
}

export function t(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  const table = MESSAGES[locale] || MESSAGES.en;
  let text: string = table[key] || MESSAGES.en[key] || key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function localizedName(
  locale: Locale,
  item?: { name?: string; name_ar?: string } | null,
) {
  if (!item) return "";
  if (locale === "ar" && item.name_ar) return item.name_ar;
  return item.name || item.name_ar || "";
}
